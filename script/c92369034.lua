function c92369034.spcon(e,c)
  if c==nil then return true end
  return Duel.GetLocationCount(c:GetControler(),LOCATION_MZONE)>0 and
  Duel.GetMatchingGroupCount(Card.IsFacedown,c:GetControler(),LOCATION_ONFIELD,LOCATION_ONFIELD,nil)>6
end
function c92369034.val(e,c)
  return Duel.GetMatchingGroupCount(Card.IsFacedown,c:GetControler(),LOCATION_ONFIELD,LOCATION_ONFIELD,nil)*1000
end
function c92369034.distg(e,c)
  return c:GetFlagEffect(92369034)~=0
end
function c92369034.target(e,tp,eg,ep,ev,re,r,rp,chk,c)
  local c=e:GetHandler()
  local i=Duel.GetMatchingGroupCount(Card.IsFacedown,c:GetControler(),LOCATION_ONFIELD,LOCATION_ONFIELD,nil)
  if chk==0 then return Duel.IsPlayerCanDraw(tp,i+1) end
  Duel.SetTargetPlayer(tp)
  Duel.SetTargetParam(i+1)
  Duel.SetOperationInfo(0,CATEGORY_DRAW,nil,0,tp,i+1)
  Duel.SetOperationInfo(0,CATEGORY_TODECK,nil,0,tp,i)
end
function c92369034.activate(e,tp,eg,ep,ev,re,r,rp,c)
  local c=e:GetHandler()
  local p=Duel.GetChainInfo(0,CHAININFO_TARGET_PLAYER)
  local i=Duel.GetMatchingGroupCount(Card.IsFacedown,c:GetControler(),LOCATION_ONFIELD,LOCATION_ONFIELD,nil)
  if Duel.Draw(p,i+1,REASON_EFFECT)==0 then return end
  if i>0 then
    Duel.ShuffleHand(tp)
    Duel.BreakEffect()
    Duel.Hint(HINT_SELECTMSG,tp,HINTMSG_TODECK)
    local g=Duel.SelectMatchingCard(tp,Card.IsAbleToDeck,tp,LOCATION_HAND,0,i,i,nil)
    if g:GetCount()>0 then
      Duel.SendtoDeck(g,nil,2,REASON_EFFECT)
    end
  end
  function c92369034.disop(e,tp,eg,ep,ev,re,r,rp)
    local c=e:GetHandler()
    local tc=Duel.GetAttackTarget()
    if tc:IsControler(tp) then tc=Duel.GetAttacker() end
    tc:RegisterFlagEffect(92369034,RESET_EVENT+RESETS_STANDARD+RESET_PHASE+PHASE_BATTLE,0,1)
  end
end
function c65846663.matfilter(c)
	return c:GetEquipCount()>2
end
function c65846663.spcon(e,c,mc)
	if c==nil then return true end
	local tp=c:GetControler()
	return Duel.GetLocationCount(tp,LOCATION_SZONE)>1
		and Duel.GetLocationCountFromEx(tp,tp,mc,c)>0
		and Duel.IsExistingMatchingCard(c65846663.spfilter1,tp,LOCATION_MZONE,0,1,nil,tp)
end
function c65846663.spfilter1(c,tp)
	return c:GetEquipCount()>2  and Duel.IsExistingMatchingCard(c65846663.spfilter2,tp,LOCATION_MZONE+LOCATION_GRAVE,0,1,c)
end
function c65846663.spfilter2(c)
	return c:IsSetCard(0x13ef) and c:IsFaceup()
end
function c65846663.spfilter3(c)
	return (c:IsSetCard(0x13ef) or c:GetEquipCount()>2) and c:IsFaceup()
end
function c65846663.spconfl(g,tp,sc)
	return g:GetCount()==2
		and g:IsExists(function(c) return c:GetEquipCount()>1 and c:IsType(0x1) end,1,nil) and g:IsExists(function(c) return c:IsType(TYPE_MONSTER) and c:IsSetCard(0x13ef) end,1,nil)
		and Duel.GetLocationCountFromEx(tp,tp,g,sc)>0
end
function c65846663.sptg(e,tp,eg,ep,ev,re,r,rp,chk,c)
	local tp=c:GetControler()
	local g=Duel.GetMatchingGroup(c65846663.spfilter3,tp,LOCATION_MZONE+LOCATION_GRAVE,0,nil)
	Duel.Hint(HINT_SELECTMSG,tp,HINTMSG_EQUIP)
	local sg=g:SelectSubGroup(tp,c65846663.spconfl,true,2,2,tp,c)
	if sg then
		local pg=e:GetLabelObject()
		pg:Clear()
		pg:Merge(sg)
		return true
	else return false end
end
function c65846663.eqop(e,tp,eg,ep,ev,re,r,rp)
	local c=e:GetHandler()
	local pg=e:GetLabelObject():GetLabelObject()
	if c:GetSummonType()==SUMMON_TYPE_SPECIAL+0x13ef and c:IsFaceup() and c:IsLocation(LOCATION_MZONE) and #pg==2 then
		for tc in aux.Next(pg) do 
			if tc:IsLocation(LOCATION_MZONE+LOCATION_GRAVE) and Duel.Equip(tp,tc,c)~=0 then
				local e1=Effect.CreateEffect(c)
				e1:SetType(EFFECT_TYPE_SINGLE)
				e1:SetProperty(EFFECT_FLAG_CANNOT_DISABLE)
				e1:SetCode(EFFECT_EQUIP_LIMIT)
				e1:SetReset(RESET_EVENT+RESETS_STANDARD)
				e1:SetLabelObject(c)
				e1:SetValue(c65846663.eqlimit)
				tc:RegisterEffect(e1)
			end
		end
		pg:Clear()
	end 
end
function c65846663.eqlimit(e,c)
	return c==e:GetLabelObject()
end
function c65846663.effcon(e,tp,eg,ep,ev,re,r,rp)
	return e:GetHandler():GetEquipCount()>=e:GetLabel()
end
function c65846663.efilter(e,te)
	return (te:GetOwner()~=e:GetOwner() and not te:GetOwner():IsType(TYPE_EQUIP))
end
function c65846663.eftg1(e,c)
	return c:IsType(TYPE_MONSTER) and c:GetEquipGroup():IsContains(e:GetHandler())
end